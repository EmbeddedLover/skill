#!/usr/bin/env python3
"""Collect lightweight bug-hunt context for embedded firmware projects."""

from __future__ import annotations

import argparse
import json
import os
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable


SKIP_DIRS = {
    ".git",
    ".svn",
    ".hg",
    ".vscode",
    ".idea",
    "__pycache__",
    "build",
    "cmake-build-debug",
    "cmake-build-release",
    "debug",
    "release",
    "node_modules",
    ".pio",
}

SOURCE_EXTS = {".c", ".cc", ".cpp", ".cxx", ".h", ".hpp", ".s", ".S", ".asm"}
TEXT_EXTS = SOURCE_EXTS | {".md", ".txt", ".ini", ".yml", ".yaml", ".json", ".ioc", ".ld", ".icf", ".sct"}

BUILD_PATTERNS = {
    "keil": [".uvprojx", ".uvoptx"],
    "iar": [".ewp", ".eww"],
    "cmake": ["CMakeLists.txt"],
    "platformio": ["platformio.ini"],
    "esp-idf": ["sdkconfig", "idf_component.yml"],
    "make": ["Makefile", "makefile"],
    "stm32cubemx": [".ioc"],
}

BOUNDARY_FILES = (
    ".ai/LLM_RULES.md",
    ".ai/LLM_BOUNDARY.md",
    ".ai/TEAM_RULES.md",
    ".ai/PROJECT_STATUS.md",
)


@dataclass(frozen=True)
class Pattern:
    bug_class: str
    pattern_id: str
    regex: str
    severity_hint: str
    focus: tuple[str, ...]
    note: str


PATTERNS = [
    Pattern("memory", "unsafe_string_copy", r"\b(strcpy|strcat|sprintf|gets)\s*\(", "high", ("memory", "protocol"), "Unbounded string/memory operation candidate."),
    Pattern("memory", "scanf_without_width", r"\b(scanf|sscanf)\s*\(", "medium", ("memory", "protocol"), "Check field widths and input bounds."),
    Pattern("memory", "raw_memcpy", r"\b(memcpy|memmove|memset)\s*\(", "medium", ("memory", "dma", "protocol"), "Check destination size and external length trust."),
    Pattern("timeout", "infinite_wait_loop", r"\bwhile\s*\([^;{}]*(HAL_|LL_|I2C|SPI|UART|USART|CAN|DMA|FLAG|BUSY|READY|TXE|RXNE)[^;{}]*\)", "high", ("timeout", "driver", "isr"), "Potential hardware wait loop; verify timeout and watchdog behavior."),
    Pattern("timeout", "wrap_unsafe_timeout", r"\b\w+\s*>\s*\w+\s*\+\s*\w+", "medium", ("timeout", "rtos"), "Potential tick wrap issue; prefer subtraction-based timeout checks."),
    Pattern("isr", "isr_delay_or_blocking", r"\b(HAL_Delay|osDelay|vTaskDelay|printf|malloc|free|fopen|fwrite|FLASH_)\s*\(", "high", ("isr",), "Potential blocking or unsafe operation; only a risk if inside ISR/callback."),
    Pattern("rtos", "critical_section", r"\b(taskENTER_CRITICAL|__disable_irq|portENTER_CRITICAL|osMutex|xSemaphore|xQueue)\b", "medium", ("rtos", "isr"), "Concurrency primitive candidate; inspect ownership and release paths."),
    Pattern("rtos", "queue_no_timeout", r"\b(xQueueReceive|xQueueSend|osMessageQueueGet|osMessageQueuePut)\s*\(", "medium", ("rtos",), "Check timeout handling and failure branch."),
    Pattern("dma", "dma_usage", r"\b(DMA|HAL_.*_DMA|SCB_CleanDCache|SCB_InvalidateDCache)\b", "medium", ("dma",), "DMA/cache/buffer lifetime candidate."),
    Pattern("flash", "flash_write_erase", r"\b(FLASH|EEPROM|NVM|HAL_FLASH|Erase|Program)\b", "high", ("flash", "storage"), "Persistent write/erase candidate; inspect power-loss and rate-limit behavior."),
    Pattern("protocol", "length_field", r"\b(len|length|size|payload_len|frame_len|rx_len)\b", "medium", ("protocol", "memory"), "Length handling candidate; inspect validation before copy/parse."),
    Pattern("state", "switch_state", r"\bswitch\s*\([^)]*(state|State|status|Status|mode|Mode)[^)]*\)", "medium", ("state",), "State machine candidate; inspect default/error/recovery paths."),
    Pattern("watchdog", "watchdog_feed", r"\b(IWDG|WWDG|Watchdog|wdg|Refresh)\b", "medium", ("watchdog", "timeout"), "Watchdog candidate; inspect feed placement and deadlock masking."),
    Pattern("generated", "generated_region", r"\b(USER CODE BEGIN|USER CODE END|Generated by|DO NOT EDIT|BEGIN OF AUTO)\b", "low", ("generated",), "Generated-code boundary candidate."),
]


def split_csv(value: str) -> list[str]:
    return [item.strip() for item in value.split(",") if item.strip()]


def rel(path: Path, root: Path) -> str:
    try:
        return path.relative_to(root).as_posix()
    except ValueError:
        return path.as_posix()


def path_matches(rel_path: str, patterns: list[str]) -> bool:
    if not patterns:
        return False
    normalized = rel_path.replace("\\", "/").lower()
    return any(pattern.replace("\\", "/").lower() in normalized for pattern in patterns)


def iter_files(root: Path, include: list[str], exclude: list[str], limit: int = 10000) -> Iterable[Path]:
    count = 0
    for current, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS and not d.startswith(".tmp")]
        for name in files:
            path = Path(current) / name
            rel_path = rel(path, root)
            if include and not path_matches(rel_path, include):
                continue
            if exclude and path_matches(rel_path, exclude):
                continue
            count += 1
            if count > limit:
                return
            yield path


def read_text(path: Path, limit_bytes: int = 512_000) -> str:
    try:
        data = path.read_bytes()[:limit_bytes]
    except OSError:
        return ""
    for encoding in ("utf-8", "utf-8-sig", "gbk", "latin-1"):
        try:
            return data.decode(encoding, errors="ignore")
        except LookupError:
            continue
    return ""


def detect_build_system(files: list[Path], root: Path) -> dict:
    found: dict[str, list[str]] = {}
    for file in files:
        name = file.name
        suffix = file.suffix
        for system, patterns in BUILD_PATTERNS.items():
            for pattern in patterns:
                if pattern.startswith(".") and suffix.lower() == pattern.lower():
                    found.setdefault(system, []).append(rel(file, root))
                elif name == pattern:
                    found.setdefault(system, []).append(rel(file, root))
    return found


def find_by_names(files: list[Path], root: Path, names: tuple[str, ...]) -> list[str]:
    wanted = tuple(n.lower() for n in names)
    return sorted(rel(f, root) for f in files if f.name.lower() in wanted)[:80]


def find_by_substrings(files: list[Path], root: Path, words: tuple[str, ...]) -> list[str]:
    results = []
    for file in files:
        p = rel(file, root)
        low = p.lower()
        if any(word in low for word in words):
            results.append(p)
    return sorted(results)[:160]


def find_by_suffixes(files: list[Path], root: Path, suffixes: tuple[str, ...]) -> list[str]:
    normalized = tuple(s.lower() for s in suffixes)
    return sorted(rel(f, root) for f in files if f.name.lower().endswith(normalized))[:120]


def collect_boundary_files(root: Path) -> dict:
    result = {}
    for item in BOUNDARY_FILES:
        path = root / item
        if path.exists() and path.is_file():
            result[item] = {"exists": True, "preview": read_text(path, 12000)[:2500]}
        else:
            result[item] = {"exists": False}
    return result


def pattern_allowed(pattern: Pattern, focus: set[str]) -> bool:
    return not focus or bool(set(pattern.focus) & focus) or pattern.bug_class in focus


def make_danger_patterns(names: list[str]) -> list[Pattern]:
    patterns = []
    for name in names:
        safe = re.escape(name)
        patterns.append(
            Pattern(
                "custom_api",
                f"custom_api:{name}",
                rf"\b{safe}\s*\(",
                "medium",
                ("custom", "api"),
                "Project-specific risky API candidate; inspect wrapper semantics and call context.",
            )
        )
    return patterns


def context_window(lines: list[str], line_no: int, radius: int) -> list[dict]:
    if radius <= 0:
        return []
    start = max(1, line_no - radius)
    end = min(len(lines), line_no + radius)
    result = []
    for idx in range(start, end + 1):
        text = re.sub(r"\s+", " ", lines[idx - 1]).strip()
        if text:
            result.append({"line": idx, "text": text[:220]})
    return result


def scan_patterns(
    files: list[Path],
    root: Path,
    focus: set[str],
    max_hits: int,
    context_lines: int,
    danger_api: list[str],
) -> list[dict]:
    hits: list[dict] = []
    all_patterns = PATTERNS + make_danger_patterns(danger_api)
    compiled = [(p, re.compile(p.regex)) for p in all_patterns if pattern_allowed(p, focus)]
    for file in files:
        if len(hits) >= max_hits:
            break
        if file.suffix not in SOURCE_EXTS:
            continue
        text = read_text(file)
        if not text:
            continue
        lines = text.splitlines()
        for idx, line in enumerate(lines, start=1):
            if len(hits) >= max_hits:
                break
            compact = re.sub(r"\s+", " ", line).strip()
            if not compact:
                continue
            for pattern, regex in compiled:
                if regex.search(line):
                    hits.append(
                        {
                            "path": rel(file, root),
                            "line": idx,
                            "bug_class": pattern.bug_class,
                            "pattern_id": pattern.pattern_id,
                            "severity_hint": pattern.severity_hint,
                            "code": compact[:220],
                            "context": context_window(lines, idx, context_lines),
                            "note": pattern.note,
                            "evidence_label": "candidate_impact",
                        }
                    )
                    break
    return hits


def summarize_classes(hits: list[dict]) -> dict:
    summary: dict[str, dict] = {}
    for hit in hits:
        cls = hit["bug_class"]
        item = summary.setdefault(cls, {"count": 0, "severity_hints": {}, "pattern_ids": {}})
        item["count"] += 1
        item["severity_hints"][hit["severity_hint"]] = item["severity_hints"].get(hit["severity_hint"], 0) + 1
        item["pattern_ids"][hit["pattern_id"]] = item["pattern_ids"].get(hit["pattern_id"], 0) + 1
    return summary


def summarize_hotspots(hits: list[dict], limit: int = 30) -> list[dict]:
    scores: dict[str, dict] = {}
    severity_weight = {"critical": 5, "high": 4, "medium": 2, "low": 1}
    for hit in hits:
        path = hit["path"]
        item = scores.setdefault(path, {"path": path, "score": 0, "hit_count": 0, "classes": set(), "top_patterns": []})
        item["score"] += severity_weight.get(hit["severity_hint"], 1)
        item["hit_count"] += 1
        item["classes"].add(hit["bug_class"])
        if len(item["top_patterns"]) < 5:
            item["top_patterns"].append(f"{hit['pattern_id']}:{hit['line']}")
    ranked = sorted(scores.values(), key=lambda x: (-x["score"], -x["hit_count"], x["path"]))
    result = []
    for item in ranked[:limit]:
        result.append(
            {
                "path": item["path"],
                "score": item["score"],
                "hit_count": item["hit_count"],
                "classes": sorted(item["classes"]),
                "top_patterns": item["top_patterns"],
            }
        )
    return result


def collect(
    root: Path,
    focus: set[str],
    include: list[str],
    exclude: list[str],
    danger_api: list[str],
    context_lines: int,
    max_hits: int,
) -> dict:
    root = root.resolve()
    files = list(iter_files(root, include=include, exclude=exclude))
    source_files = [f for f in files if f.suffix in SOURCE_EXTS]
    hits = scan_patterns(source_files, root, focus, max_hits=max_hits, context_lines=context_lines, danger_api=danger_api)

    context = {
        "ok": True,
        "project_root": str(root),
        "summary": {
            "file_count_scanned": len(files),
            "source_file_count": len(source_files),
            "focus": sorted(focus),
            "include": include,
            "exclude": exclude,
            "danger_api": danger_api,
            "context_lines": context_lines,
            "candidate_hit_count": len(hits),
        },
        "build_systems": detect_build_system(files, root),
        "entry_points": {
            "main_files": find_by_names(files, root, ("main.c", "main.cpp", "app_main.c")),
            "startup_files": find_by_substrings(files, root, ("startup_", "vectors", "vector_table")),
            "linker_scripts": find_by_suffixes(files, root, (".ld", ".icf", ".sct")),
        },
        "hints": {
            "isr_callback": find_by_substrings(source_files, root, ("isr", "irq", "callback", "it.c", "interrupt")),
            "rtos": find_by_substrings(files, root, ("freertos", "rt-thread", "zephyr", "cmsis_os", "tx_api")),
            "protocol": find_by_substrings(files, root, ("can", "uart", "usart", "spi", "i2c", "modbus", "ethernet", "tcp", "udp", "usb", "protocol", "parser")),
            "storage": find_by_substrings(files, root, ("flash", "eeprom", "nvm", "storage", "littlefs", "fatfs")),
            "dma": find_by_substrings(files, root, ("dma", "cache", "buffer")),
            "tests": find_by_substrings(files, root, ("test", "tests", "unity", "ceedling", "cpputest", "gtest")),
        },
        "ai_boundary_files": collect_boundary_files(root),
        "class_summary": summarize_classes(hits),
        "hotspots": summarize_hotspots(hits),
        "candidate_hits": hits,
        "evidence_note": "All scanner hits are candidate_impact. Deep-read surrounding source before reporting confirmed_issue.",
        "warnings": [],
    }

    if len(files) >= 10000:
        context["warnings"].append("File scan limit reached; context may be incomplete.")
    if not context["build_systems"]:
        context["warnings"].append("No common embedded build system marker found.")
    if not context["entry_points"]["main_files"]:
        context["warnings"].append("No main.c/main.cpp/app_main.c entry point found.")
    if not any(item.get("exists") for item in context["ai_boundary_files"].values()):
        context["warnings"].append("No .ai boundary/status files found.")
    if not hits:
        context["warnings"].append("No candidate pattern hits found for selected focus.")
    return context


def main() -> int:
    parser = argparse.ArgumentParser(description="Collect lightweight embedded bug-hunt context.")
    parser.add_argument("--project-root", default=".", help="Embedded project root.")
    parser.add_argument(
        "--focus",
        default="",
        help="Comma-separated focus classes: memory,timeout,isr,rtos,dma,flash,storage,protocol,state,watchdog,generated,driver.",
    )
    parser.add_argument("--include", default="", help="Comma-separated path substrings to include.")
    parser.add_argument("--exclude", default="", help="Comma-separated path substrings to exclude.")
    parser.add_argument("--danger-api", default="", help="Comma-separated project-specific risky API names to match.")
    parser.add_argument("--context-lines", type=int, default=2, help="Number of surrounding lines to include for each hit.")
    parser.add_argument("--max-hits", type=int, default=300, help="Maximum candidate hits to include.")
    parser.add_argument("--output", help="Optional JSON output path.")
    args = parser.parse_args()

    root = Path(args.project_root)
    if not root.exists() or not root.is_dir():
        data = {"ok": False, "error": f"Project root is not a directory: {root}"}
    else:
        focus = {item.strip().lower() for item in args.focus.split(",") if item.strip()}
        data = collect(
            root,
            focus,
            include=split_csv(args.include),
            exclude=split_csv(args.exclude),
            danger_api=split_csv(args.danger_api),
            context_lines=max(0, args.context_lines),
            max_hits=max(1, args.max_hits),
        )

    text = json.dumps(data, ensure_ascii=False, indent=2)
    if args.output:
        Path(args.output).write_text(text + "\n", encoding="utf-8")
    else:
        print(text)
    return 0 if data.get("ok") else 2


if __name__ == "__main__":
    raise SystemExit(main())
